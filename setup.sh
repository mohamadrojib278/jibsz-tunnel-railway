deploy_project_files() {
    log_info "Menyiapkan direktori proyek di ${INSTALL_DIR} dan ${CONFIG_DIR}..."
    touch /etc/jibsz/blocked_ips.map 2>/dev/null || true
    mkdir -p "${INSTALL_DIR}" "${CONFIG_DIR}" "${CONFIG_DIR}/ssl" "${LOG_DIR}"
    chmod 777 "${LOG_DIR}" 2>/dev/null || true

    local script_dir
    script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

    if [[ -d "${script_dir}/backend" && -d "${script_dir}/webpanel" && -d "${script_dir}/cli" ]]; then
        log_info "Menyalin file proyek terbaru dari (${script_dir})..."
        cp -rf "${script_dir}/backend" "${INSTALL_DIR}/"
        cp -rf "${script_dir}/webpanel" "${INSTALL_DIR}/"
        cp -rf "${script_dir}/cli" "${INSTALL_DIR}/"
        cp -f "${script_dir}/README.md" "${INSTALL_DIR}/" 2>/dev/null || true
        cp -f "${script_dir}/setup.sh" "${INSTALL_DIR}/" 2>/dev/null || true
    else
        log_info "Mengunduh repositori proyek dari GitHub (${REPO_GIT_URL})..."
        rm -rf /tmp/jibsz-clone
        if git clone --depth 1 "${REPO_GIT_URL}" /tmp/jibsz-clone; then
            cp -rf /tmp/jibsz-clone/* "${INSTALL_DIR}/"
            rm -rf /tmp/jibsz-clone
        else
            log_err "Gagal meng-clone repositori GitHub. Pastikan koneksi internet aktif atau jalankan dari folder ekstrak ZIP."
            exit 1
        fi
    fi

    chmod +x "${INSTALL_DIR}/backend/installer_engine.sh"
    chmod +x "${INSTALL_DIR}/backend/ssh_ws_proxy.py"
    chmod +x "${INSTALL_DIR}/cli/"*.sh

    ln -sf "${INSTALL_DIR}/cli/menu.sh" /usr/local/bin/menu
    ln -sf "${INSTALL_DIR}/cli/menu.sh" /usr/local/bin/jibsz
    ln -sf "${INSTALL_DIR}/cli/manage_ssh.sh" /usr/local/bin/menu-ssh
    ln -sf "${INSTALL_DIR}/cli/manage_xray.sh" /usr/local/bin/menu-vmess
    ln -sf "${INSTALL_DIR}/cli/manage_xray.sh" /usr/local/bin/menu-vless
    ln -sf "${INSTALL_DIR}/cli/manage_xray.sh" /usr/local/bin/menu-trojan
    ln -sf "${INSTALL_DIR}/cli/menu.sh" /usr/local/bin/menu-autodel
    ln -sf "${INSTALL_DIR}/cli/menu.sh" /usr/local/bin/menu-system

    cat <<EOF > /etc/cron.d/jibsz-monitor
SHELL=/bin/bash
PATH=/usr/local/sbin:/usr/local/bin:/sbin:/bin:/usr/sbin:/usr/bin
* * * * * root /usr/bin/flock -n /run/jibsz-monitor.lock /usr/bin/timeout 45 ${INSTALL_DIR}/cli/monitor_ip_quota.sh --cron >> ${LOG_DIR}/monitor.log 2>&1
EOF
    chmod 644 /etc/cron.d/jibsz-monitor
    systemctl restart cron 2>/dev/null || service cron restart 2>/dev/null || true

    cat << 'EOF' > /etc/logrotate.d/jibsz-tunnel
/var/log/jibsz/*.log {
    daily
    rotate 3
    size 10M
    missingok
    notifempty
    compress
    delaycompress
    copytruncate
}
EOF
    chmod 644 /etc/logrotate.d/jibsz-tunnel 2>/dev/null || true

    # Lindungi OpenSSH (sshd) dari Linux OOM Killer agar VPS selalu bisa diakses SSH
    for ssh_svc in ssh sshd; do
        mkdir -p "/etc/systemd/system/${ssh_svc}.service.d" 2>/dev/null || true
        cat << 'EOF' > "/etc/systemd/system/${ssh_svc}.service.d/jibsz-oom-protect.conf"
[Service]
OOMScoreAdjust=-1000
EOF
    done

    # Buat Swap 1GB otomatis jika VPS belum punya swap dan RAM <= 2GB (cegah freeze/OOM)
    if [[ -z "$(swapon --show 2>/dev/null)" ]] && [[ ! -f /swapfile ]]; then
        local total_ram_mb avail_disk_mb
        total_ram_mb=$(awk '/MemTotal/ {print int($2/1024)}' /proc/meminfo 2>/dev/null || echo 0)
        avail_disk_mb=$(df -m / 2>/dev/null | awk 'NR==2 {print $4}' || echo 0)
        if (( total_ram_mb > 0 && total_ram_mb <= 2200 && avail_disk_mb >= 3000 )); then
            if fallocate -l 1G /swapfile 2>/dev/null || dd if=/dev/zero of=/swapfile bs=1M count=1024 status=none 2>/dev/null; then
                chmod 600 /swapfile
                if mkswap /swapfile >/dev/null 2>&1 && swapon /swapfile 2>/dev/null; then
                    grep -q '^/swapfile ' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
                    sysctl -w vm.swappiness=20 >/dev/null 2>&1 || true
                    log_ok "Swap 1GB otomatis diaktifkan untuk stabilitas jangka panjang."
                else
                    rm -f /swapfile 2>/dev/null || true
                fi
            fi
        fi
    fi

    log_ok "Seluruh file proyek, Cron Monitoring, dan symlink perintah CLI (termasuk menu-autodel) berhasil dipasang."
}

